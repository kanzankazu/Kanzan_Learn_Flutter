/// Phase 10.6 — Topic 02: gRPC (Google Remote Procedure Call)
///
/// gRPC uses Protocol Buffers (protobuf) for serialization and HTTP/2
/// for transport. It is faster and more efficient than REST+JSON for
/// high-throughput services.
///
/// When to use gRPC vs REST vs GraphQL:
/// - gRPC: service-to-service, streaming, mobile ↔ backend (same team)
/// - REST: public APIs, browser clients, third-party integrations
/// - GraphQL: flexible client queries, BFF (Backend For Frontend)
///
/// Key concepts covered:
/// 1. .proto file — service and message definitions
/// 2. protoc — generates Dart stubs from .proto
/// 3. Unary RPC — one request, one response
/// 4. Server streaming — one request, many responses over time
/// 5. Client streaming — many requests, one response
/// 6. Bidirectional streaming — many requests, many responses
/// 7. Metadata — authentication headers
/// 8. Interceptors — logging, auth, retry
