// gRPC interceptors are like HTTP middleware — applied to every call

class AuthInterceptor implements ClientInterceptor {
  final TokenStorage _storage;
  const AuthInterceptor(this._storage);

  @override
  ResponseFuture<R> interceptUnary<Q, R>(
    ClientMethod<Q, R> method,
    Q request,
    CallOptions options,
    ClientUnaryInvoker<Q, R> invoker,
  ) {
    // Add auth token to every unary call
    final token = _storage.getAccessToken();
    final newOptions = options.mergedWith(CallOptions(
      metadata: {'authorization': 'Bearer $token'},
    ));
    return invoker(method, request, newOptions);
  }

  // Also intercept streaming calls...
}

// Register interceptor on the stub:
_stub = ChatServiceClient(
  _channel,
  interceptors: [AuthInterceptor(_storage), LoggingInterceptor()],
);'''),

