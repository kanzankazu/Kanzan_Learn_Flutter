// protos/chat.proto
syntax = "proto3";

package chat;

option dart_out = "lib/src/generated";  // output directory

// Message types (like classes, serialized to binary)
message ChatMessage {
  string id = 1;           // field number — determines binary encoding
  string sender_id = 2;
  string content = 3;
  int64  timestamp = 4;    // Unix milliseconds
}

message SendMessageRequest {
  string chat_room_id = 1;
  string content = 2;
}

message SendMessageResponse {
  ChatMessage message = 1;
  bool success = 2;
}

message StreamMessagesRequest {
  string chat_room_id = 1;
  int64  since_timestamp = 2;
}

// Service definition — what the server exposes
service ChatService {
  // Unary: one request → one response (like HTTP GET/POST)
  rpc SendMessage(SendMessageRequest) returns (SendMessageResponse);

  // Server streaming: one request → many responses over time
  rpc StreamMessages(StreamMessagesRequest) returns (stream ChatMessage);

  // Bidirectional streaming: continuous message exchange
  rpc ChatStream(stream ChatMessage) returns (stream ChatMessage);
}

# Generate Dart code:
dart pub global activate protoc_plugin
protoc --dart_out=grpc:lib/src/generated --plugin=protoc-gen-dart protos/chat.proto'''),

