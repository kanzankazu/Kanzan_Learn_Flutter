// lib/features/counter/providers/counter_provider.dart
import 'package:riverpod_annotation/riverpod_annotation.dart';
part 'counter_provider.g.dart';

// @riverpod on a class = generates a NotifierProvider<Counter, int>
// The class MUST extend _$ClassName (generated mixin with ref, state)
@riverpod
class Counter extends _$Counter {
  // build() = initial state (called once when first watched)
  @override
  int build() => 0;

  void increment() => state++;
  void decrement() => state = (state - 1).clamp(0, 999);
  void reset() => state = 0;
}

