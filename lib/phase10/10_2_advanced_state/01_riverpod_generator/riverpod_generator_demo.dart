/// Phase 10.2 — Topic 01: Riverpod Generator
///
/// Riverpod Generator eliminates boilerplate by auto-generating provider
/// declarations from annotated functions and classes.
///
/// Without generator → you declare providers manually:
///   final counterProvider = StateNotifierProvider<CounterNotifier, int>(...)
///
/// With generator → you annotate and run build_runner:
///   @riverpod
///   class Counter extends _$Counter { ... }
///   // build_runner generates: counterProvider automatically
///
/// Key concepts covered:
/// 1. Setup: riverpod_annotation + riverpod_generator + build_runner
/// 2. @riverpod annotation for functions (simple providers)
/// 3. @Riverpod(keepAlive: true) — control auto-disposal
/// 4. Class-based notifiers: @riverpod class MyNotifier extends _$MyNotifier
/// 5. AsyncNotifierProvider — async data with loading/error/data states
/// 6. Family providers — parameterized providers via arguments
/// 7. Provider dependencies — ref.watch inside generated providers
/// 8. Testing generated providers — ProviderContainer overrides
///
/// How to regenerate after changing annotated code:
/// ```bash
/// dart run build_runner build --delete-conflicting-outputs
/// # or watch mode:
/// dart run build_runner watch --delete-conflicting-outputs
/// ```
