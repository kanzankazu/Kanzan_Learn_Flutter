// lib/features/transactions/providers/transaction_list_provider.dart
import 'package:riverpod_annotation/riverpod_annotation.dart';
part 'transaction_list_provider.g.dart';

@riverpod
class TransactionList extends _$TransactionList {
  // build() returns Future<T> → generates AsyncNotifierProvider
  // state is AsyncValue<List<Transaction>> automatically
  @override
  Future<List<Transaction>> build() async {
    // Automatically cancelled and rerun when dependencies change
    final repo = ref.watch(transactionRepoProvider);
    return repo.getAll();
  }

  // Optimistic add: update state immediately, then confirm
  Future<void> add(Transaction tx) async {
    // 1. Add to current list optimistically
    final current = state.requireValue;
    state = AsyncData([tx, ...current]);

    // 2. Persist to backend
    try {
      final saved = await ref.read(transactionRepoProvider).add(tx);
      // 3. Replace with server version (has ID)
      state = AsyncData([saved, ...current]);
    } catch (e, st) {
      // 4. Roll back on failure
      state = AsyncData(current);
      state = AsyncError(e, st);
    }
  }

  // Invalidate = dispose + re-run build() on next watch
  Future<void> refresh() => ref.refresh(transactionListProvider.future);
}

// Widget usage:
// final txs = ref.watch(transactionListProvider);
// txs.when(
//   loading: () => CircularProgressIndicator(),
//   error:   (e, _) => Text('Error: $e'),
//   data:    (list) => TransactionList(items: list),
