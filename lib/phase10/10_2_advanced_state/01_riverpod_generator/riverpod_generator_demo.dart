// lib/features/settings/providers/theme_provider.dart

import 'package:riverpod_annotation/riverpod_annotation.dart';
part 'theme_provider.g.dart';   // ← generated file

// @riverpod on a function = generates a Provider<T>
// The function body IS the provider's build logic
@riverpod
ThemeMode themeMode(ThemeModeRef ref) {
  // Read from SharedPreferences, Hive, etc.
  return ThemeMode.system;  // default
}

// @Riverpod(keepAlive: true) = provider is NEVER auto-disposed
// Use for global singletons (analytics, auth, etc.)
@Riverpod(keepAlive: true)
AppConfig appConfig(AppConfigRef ref) => AppConfig.fromEnv();

// Async function provider = generates FutureProvider<T>
@riverpod
Future<User> currentUser(CurrentUserRef ref) async {
  // ref is automatically typed as CurrentUserRef
  final auth = ref.watch(authServiceProvider);
  return auth.getCurrentUser();
}

