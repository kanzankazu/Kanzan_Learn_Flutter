// Parameterized providers: one provider definition, many instances
// Each unique argument gets its own independent instance

@riverpod
Future<Transaction> transaction(TransactionRef ref, String id) async {
  // id is passed as a parameter — each id creates a separate provider
  return ref.watch(transactionRepoProvider).getById(id);
}

// Family notifier — stateful and parameterized
@riverpod
class TransactionDetail extends _$TransactionDetail {
  @override
  Future<Transaction> build(String id) async {
    return ref.watch(transactionRepoProvider).getById(id);
  }

  Future<void> delete() async {
    final id = arg; // 'arg' gives you the family parameter
    await ref.read(transactionRepoProvider).delete(id);
    ref.invalidateSelf(); // triggers rebuild/error state
  }
}

// Widget usage:
// final tx = ref.watch(transactionProvider('tx_123'));
// ref.read(transactionDetailProvider('tx_123').notifier).delete();

// IMPORTANT: Use @riverpod on families only when the parameter is:
// - A primitive (String, int, enum) — has consistent equality
// - An immutable value object with == overridden
// NEVER pass a mutable object (List, Map) as a family argument.'''),

