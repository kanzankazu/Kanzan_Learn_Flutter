// Providers can watch/read other providers — build_runner handles the wiring
@riverpod
class SearchResults extends _$SearchResults {
  @override
  Future<List<Transaction>> build(String query) async {
    // Debounce: wait 300ms before fetching (avoids too many requests)
    await Future.delayed(const Duration(milliseconds: 300));

    // Watch other providers — this provider re-runs when they change
    final repo  = ref.watch(transactionRepoProvider);
    final filter = ref.watch(activeFilterProvider);

    // Combine query + filter
    return repo.search(query: query, filter: filter);
  }
}

// ref.watch vs ref.read inside a provider:
// ref.watch(x) → rebuilds THIS provider when x changes
// ref.read(x)  → one-time read, no rebuild subscription
// ref.listen(x, (prev, next) => ...) → side effect on change (e.g. analytics)'''),

