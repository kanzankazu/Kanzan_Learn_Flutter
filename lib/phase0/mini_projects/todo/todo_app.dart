// CLASS — TodoManager
// ============================================================

/// Manages a collection of [TodoItem]s with full CRUD operations.
///
/// **Concepts demonstrated:**
/// - Encapsulation: `_todos` and `_nextId` are private (not directly accessible)
/// - List operations: add, remove (with `removeWhere`), filter (`where`)
/// - Auto-increment ID using `_nextId`
/// - Meaningful return values: `bool` to signal success/failure
///
/// Example usage:
/// ```dart
/// final manager = TodoManager();
/// manager.addTodo('Buy milk');
/// manager.toggleTodo(1);  // returns true if id found
/// manager.removeTodo(1);  // returns true if id found
/// ```
class TodoManager {
  // ── Private Fields ──────────────────────────────────────────
  // Prefixed with `_` so they cannot be accessed from outside the class.
  // This is the Encapsulation concept in OOP.

  /// List of all to-do items (private, managed internally).
  final List<TodoItem> _todos = [];

  /// Counter for the next ID — incremented each time an item is added.
  int _nextId = 1;

  // ── Methods ─────────────────────────────────────────────────

  /// Adds a new task to the list.
  ///
  /// [title] must not be empty (validated before calling this method).
  /// Returns the newly created [TodoItem] (useful for confirmation).
  ///
  /// ID is assigned automatically from [_nextId], then incremented.
  TodoItem addTodo(String title) {
    // Create a new item with the generated ID
    final item = TodoItem(id: _nextId, title: title);

    // Add it to the list
    _todos.add(item);

    // Increment the ID for the next item
    _nextId++;

    return item;
  }

  /// Removes an item by [id].
  ///
  /// Returns `true` if an item with the given [id] was found and
  /// successfully removed. Returns `false` if not found.
  ///
  /// Uses `removeWhere` — removes elements that satisfy the condition.
  bool removeTodo(int id) {
    // Check first whether an item with this id exists
    final previousLength = _todos.length;

    // removeWhere: remove all elements whose condition is true
    // Here: remove the item whose id matches the requested one
    _todos.removeWhere((item) => item.id == id);

    // If the list length changed, something was removed → return true
    return _todos.length < previousLength;
  }

  /// Flips the done/not-done status of the item with the given [id].
  ///
  /// Returns `true` if the item was found and toggled successfully.
  /// Returns `false` if no item with the given [id] exists.
  bool toggleTodo(int id) {
    // Find the item with the matching id
    // `where` + `firstOrNull` — safer than `firstWhere` which throws an error
    try {
      final item = _todos.firstWhere((item) => item.id == id);
      item.toggleDone();
      return true; // found & toggled successfully
    } catch (_) {
      return false; // not found
    }
  }

  /// Returns an unmodifiable copy of all items (pending + completed).
  ///
  /// Returns `List.unmodifiable` so it cannot be changed from outside.
  /// This protects the internal `_todos` from unexpected modifications.
  List<TodoItem> getAllTodos() {
    // `List.unmodifiable` → read-only, cannot add/remove from outside
    return List.unmodifiable(_todos);
  }

  /// Returns items that are NOT yet done (`isDone == false`).
  ///
  /// Uses `.where()` for filtering — this is a higher-order function
  /// that accepts a function (condition) as an argument.
  List<TodoItem> getPendingTodos() {
    // `.where()` → return an iterable that satisfies the condition
    // `.toList()` → convert the iterable to a List
    return _todos.where((item) => !item.isDone).toList();
  }

  /// Returns items that ARE completed (`isDone == true`).
  ///
  /// Same as [getPendingTodos] but with the opposite condition.
  List<TodoItem> getCompletedTodos() {
    return _todos.where((item) => item.isDone).toList();
  }
}

