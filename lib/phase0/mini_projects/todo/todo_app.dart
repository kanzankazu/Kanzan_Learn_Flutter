// MAIN — Entry Point + Menu Loop
// ============================================================

/// Entry point of the To-Do List CLI application.
///
/// Displays an interactive menu and reads input from the user.
/// The loop keeps running until the user selects the "Exit" option.
///
/// **Concepts practiced in main():**
/// - while loop (menu loop)
/// - switch/case for menu routing
/// - stdin.readLineSync() for reading input
/// - Input validation (empty title, id must be a number)
void main() {
  // Opening banner
  _printBanner();

  // Create manager — this is one "session" of our to-do list
  final manager = TodoManager();

  // ── Menu Loop ───────────────────────────────────────────────
  // Keep looping while `isRunning` is still true.
  // User can exit by choosing option 7 (Exit).
  bool isRunning = true;

  while (isRunning) {
    _printMenu();

    // Read the user's choice from keyboard
    final input = stdin.readLineSync()?.trim() ?? '';

    // Route based on menu selection
    switch (input) {
      case '1':
        _handleAddTodo(manager);
      case '2':
        _handleViewAll(manager);
      case '3':
        _handleViewPending(manager);
      case '4':
        _handleViewCompleted(manager);
      case '5':
        _handleToggleTodo(manager);
      case '6':
        _handleDeleteTodo(manager);
      case '7':
        // Set flag to exit the while loop
        isRunning = false;
        print('\n👋 See you! Don\'t forget to get those tasks done!\n');
      default:
        // Invalid input — show error message
        print('\n⚠️  Choice "$input" is not valid. Enter a number 1-7.\n');
    }
  }
}

// ============================================================
// HELPER FUNCTIONS — Handler per Menu Item
// ============================================================

/// Adds a new to-do via user input.
///
/// Validates that the title is not empty before calling [TodoManager.addTodo].
void _handleAddTodo(TodoManager manager) {
  print('\n── Add New Task ──');
  stdout.write('Task title: ');
  final title = stdin.readLineSync()?.trim() ?? '';

  // Validation: title must not be empty
  if (title.isEmpty) {
    print('❌ Title cannot be empty. Task was not added.\n');
    return; // exit the function without adding
  }

  // Add to manager and capture the result
  final item = manager.addTodo(title);
  print('✅ Task added: $item\n');
}

/// Displays all to-dos (pending + completed).
void _handleViewAll(TodoManager manager) {
  print('\n── All Tasks ──');
  final todos = manager.getAllTodos();

  if (todos.isEmpty) {
    print('📋 No tasks yet. Add one with menu [1].\n');
    return;
  }

  // Show a stats summary first
  final completed = todos.where((t) => t.isDone).length;
  final pending = todos.length - completed;
  print('Total: ${todos.length} tasks  |  ✓ Completed: $completed  |  ○ Pending: $pending\n');

  // Display each item — toString() is already overridden in TodoItem
  for (final item in todos) {
    print('  $item');
  }
  print('');
}

/// Displays only pending (not-yet-done) to-dos.
void _handleViewPending(TodoManager manager) {
  print('\n── Pending Tasks (Not Done) ──');
  final pending = manager.getPendingTodos();

  if (pending.isEmpty) {
    print('🎉 No pending tasks. Everything is done!\n');
    return;
  }

  print('There are ${pending.length} unfinished tasks:\n');
  for (final item in pending) {
    print('  $item');
  }
  print('');
}

/// Displays only completed to-dos.
void _handleViewCompleted(TodoManager manager) {
  print('\n── Completed Tasks ──');
  final completed = manager.getCompletedTodos();

  if (completed.isEmpty) {
    print('📭 No completed tasks yet.\n');
    return;
  }

  print('${completed.length} tasks completed:\n');
  for (final item in completed) {
    print('  $item');
  }
  print('');
}

/// Asks the user for an ID and toggles the status of that task.
void _handleToggleTodo(TodoManager manager) {
  print('\n── Toggle Task Status ──');

  // Show all tasks first so the user knows their IDs
  final todos = manager.getAllTodos();
  if (todos.isEmpty) {
    print('📋 No tasks to toggle.\n');
    return;
  }

  // Show a brief list
  for (final item in todos) {
    print('  $item');
  }

  stdout.write('\nEnter the ID of the task to toggle: ');
  final inputId = stdin.readLineSync()?.trim() ?? '';

  // Validation: input must be a number
  final id = int.tryParse(inputId);
  if (id == null) {
    print('❌ "$inputId" is not a valid number.\n');
    return;
  }

  // Toggle and check the result
  final success = manager.toggleTodo(id);
  if (success) {
    // Find the newly toggled item to show its new status
    final item = manager.getAllTodos().firstWhere((t) => t.id == id);
    final newStatus = item.isDone ? 'DONE ✓' : 'PENDING ○';
    print('✅ Task #$id is now: $newStatus\n');
  } else {
    print('❌ No task found with ID #$id.\n');
  }
}

/// Asks the user for an ID and deletes that task.
void _handleDeleteTodo(TodoManager manager) {
  print('\n── Delete Task ──');

  final todos = manager.getAllTodos();
  if (todos.isEmpty) {
    print('📋 No tasks to delete.\n');
    return;
  }

  // Show the list so the user knows available IDs
  for (final item in todos) {
    print('  $item');
  }

  stdout.write('\nEnter the ID of the task to delete: ');
  final inputId = stdin.readLineSync()?.trim() ?? '';

  // Validation: must be a number
  final id = int.tryParse(inputId);
  if (id == null) {
    print('❌ "$inputId" is not a valid number.\n');
    return;
  }

  // Confirm before deleting
  stdout.write('Are you sure you want to delete task #$id? (y/n): ');
  final confirmation = stdin.readLineSync()?.trim().toLowerCase() ?? '';

  if (confirmation != 'y' && confirmation != 'yes') {
    print('🚫 Deletion cancelled.\n');
    return;
  }

  // Delete and check the result
  final success = manager.removeTodo(id);
  if (success) {
    print('🗑️  Task #$id successfully deleted.\n');
  } else {
    print('❌ No task found with ID #$id.\n');
  }
}

