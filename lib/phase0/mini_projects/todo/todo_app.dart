// CLASS — TodoItem
// ============================================================

/// Represents a single to-do item in the application.
///
/// **Concepts demonstrated:**
/// - Class with multiple field types (int, String, bool, DateTime)
/// - `final` vs non-final fields
/// - Simple instance methods
/// - Override `toString()` for nice display
///
/// Each item has a unique ID, a title, a done/pending status, and
/// a creation timestamp. Status can be toggled (flipped) via `toggleDone()`.
class TodoItem {
  /// Unique ID for this item (auto-generated by [TodoManager]).
  final int id;

  /// Title or short description of the task.
  final String title;

  /// Whether this task has been completed.
  ///
  /// `false` = still pending/not done.
  /// `true`  = completed.
  bool isDone;

  /// Timestamp of when this item was created (auto-set on construction).
  final DateTime createdAt;

  // ── Constructor ─────────────────────────────────────────────
  // `id` and `title` are provided externally (by TodoManager).
  // `isDone` defaults to false — new tasks are always not done yet.
  // `createdAt` is auto-set to the current time.
  /// Creates a new to-do item.
  ///
  /// [id] must be unique (generated by [TodoManager]).
  /// [title] is the task title, must not be empty.
  /// [isDone] defaults to `false` — new tasks are always not done yet.
  TodoItem({required this.id, required this.title, this.isDone = false})
      : createdAt = DateTime.now();

  // ── Instance Method ─────────────────────────────────────────

  /// Flips the done/not-done status (toggle).
  ///
  /// If `isDone` was `false` → becomes `true`, and vice versa.
  /// Example:
  /// ```dart
  /// item.isDone; // false
  /// item.toggleDone();
  /// item.isDone; // true
  /// ```
  void toggleDone() {
    // `!` is the NOT operator — flips the bool value
    isDone = !isDone;
  }

  // ── Override toString() ─────────────────────────────────────

  /// Displays the to-do item in a human-readable format.
  ///
  /// Output format: `[✓] #1 Buy milk  (created: 14:30)`
  ///
  /// Overrides `Object.toString()` — automatically used when
  /// we `print(item)` or interpolate `'$item'`.
  @override
  String toString() {
    // Status icon: checkmark if done, empty box if not
    final statusIcon = isDone ? '✓' : ' ';

    // Format creation time — only show hour:minute for brevity
    final createdTime = _formatTime(createdAt);

    // Title with strikethrough effect (terminal doesn't support ~~,
    // so we use square brackets instead)
    final titleDisplay = isDone ? '[$title]' : title;

    return '[$statusIcon] #$id $titleDisplay  (created: $createdTime)';
  }

  // Format hour:minute:second from a DateTime
  // Private helper — only used inside this class
  String _formatTime(DateTime dt) {
    // padLeft(2, '0') → always ensure 2 digits, e.g. "9" → "09"
    final hour = dt.hour.toString().padLeft(2, '0');
    final minute = dt.minute.toString().padLeft(2, '0');
    final second = dt.second.toString().padLeft(2, '0');
    return '$hour:$minute:$second';
  }
}

